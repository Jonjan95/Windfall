# Builds Data/Recipes.lua from the Forever ("Camelot") recipe lists in the
# What's Training? addon by Sveng (MIT licence, see Data/THIRD_PARTY.md).
#
# Keeps what a levelling plan needs: recipes a trainer teaches (or that come
# with the profession), with the skill they unlock at, the trainer's price and
# the item they make, plus the rank you train to raise the skill cap.
#
# Usage: python -I tools/import_recipes.py <WhatsTraining folder>
import os
import re
import sys

SRC = os.path.join(sys.argv[1], "Crafting", "Recipes", "Camelot")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Data", "Recipes.lua")

# Crafting professions, by skill line.
FILES = {
    171: "Alchemy", 164: "Blacksmithing", 185: "Cooking", 333: "Enchanting",
    202: "Engineering", 129: "FirstAid", 165: "Leatherworking", 197: "Tailoring",
}

ENTRY = re.compile(r"^\s*\{ spell = (\d+), skill = (\d+)(.*)\},?\s*$")


def field(rest, name):
    m = re.search(r"\b" + name + r" = (\d+)", rest)
    return int(m.group(1)) if m else None


def sources(rest):
    m = re.search(r"source = \{([^}]*)\}", rest)
    return re.findall(r'"(\w+)"', m.group(1)) if m else []


lines = [
    "-- Generated by tools/import_recipes.py from What's Training? by Sveng (MIT).",
    "-- Forever recipes a trainer teaches, by skill line:",
    "--   { spell, skill it unlocks at, trainer price in copper (0 = comes with the profession), item made }",
    "-- and ranks: { rank = name, spell, skill, price, level needed, how }.",
    "local _, ns = ...",
    "ns.TrainerRecipes = {",
]
total = 0
for line_id, name in sorted(FILES.items()):
    path = os.path.join(SRC, name + ".lua")
    recipes, ranks = [], []
    for raw in open(path, encoding="utf-8"):
        m = ENTRY.match(raw)
        if not m:
            continue
        spell, skill, rest = int(m.group(1)), int(m.group(2)), m.group(3)
        src = sources(rest)
        rank = re.search(r'rank = "(\w+)"', rest)
        if rank:
            how = "trainer" if "trainer" in src else (src[0] if src else "trainer")
            ranks.append('        { rank = "%s", %d, %d, %d, %d, "%s" },' % (
                rank.group(1), spell, skill, field(rest, "cost") or 0, field(rest, "level") or 0, how))
            continue
        if src and "trainer" not in src:
            continue  # drops, vendors, quests and reputation are not part of the plan
        creates = field(rest, "creates")
        recipes.append("        { %d, %d, %d, %s }," % (spell, skill, field(rest, "cost") or 0, creates or "nil"))
    total += len(recipes)
    lines.append("    [%d] = { -- %s" % (line_id, name))
    lines += recipes + ranks
    lines.append("    },")
lines.append("}")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("wrote", OUT, total, "recipes")
